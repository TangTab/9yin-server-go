package main

import (
	"fmt"
	"go/format"
	"io"
	"os"
	"strings"
)

func osStderr() io.Writer { return os.Stderr }

// genCatalog 生成 custom_gen.go（已 gofmt）。
func genCatalog(c2s, s2c []MsgDef) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/protogen from testdata/lua/share/*_custom_define.lua; DO NOT EDIT.\n\n")
	b.WriteString("package proto\n\n")

	b.WriteString(`// CustomMsgDef 一条自定义消息的目录定义。
// Fields 是从“格式：”注释尽力解析出的 TVarList 类型标签序列
// （2=int32 3=int64 4=float32 5=float64 6=string 7=widestr 8=object），
// VarArgs 表示尾部存在可变参数表；权威描述以 Format 原文为准。
type CustomMsgDef struct {
	Name    string // lua 常量名
	Key     string // S2C 字符串消息名（C2S 为空）
	ID      uint32 // C2S 数值 ID（S2C 为 0）
	Desc    string
	Format  string
	Fields  []byte
	VarArgs bool
}

`)

	fmt.Fprintf(&b, "// C2SCustomByID C2S 自定义消息（client_custom_define.lua，共 %d 条）。\n", len(c2s))
	b.WriteString("var C2SCustomByID = map[uint32]CustomMsgDef{\n")
	seenID := map[uint32]bool{}
	for _, d := range c2s {
		if d.ID == 0 {
			continue
		}
		if seenID[d.ID] {
			fmt.Fprintf(osStderr(), "protogen: 警告 C2S ID %d 重复（%s），保留首个\n", d.ID, d.Name)
			continue
		}
		seenID[d.ID] = true
		writeDef(&b, d, fmt.Sprintf("%d:", d.ID))
	}
	b.WriteString("}\n\n")

	b.WriteString("// C2SCustomByName 按常量名索引（供代码按语义引用）。\nvar C2SCustomByName = map[string]uint32{\n")
	for _, d := range c2s {
		if d.ID == 0 {
			continue
		}
		fmt.Fprintf(&b, "\t%q: %d,\n", d.Name, d.ID)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// S2CCustomByKey S2C 自定义消息（server_custom_define.lua，共 %d 条）。\n", len(s2c))
	b.WriteString("var S2CCustomByKey = map[string]CustomMsgDef{\n")
	seenKey := map[string]bool{}
	for _, d := range s2c {
		if d.Key == "" {
			continue
		}
		if seenKey[d.Key] {
			fmt.Fprintf(osStderr(), "protogen: 警告 S2C key %q 重复（%s），保留首个\n", d.Key, d.Name)
			continue
		}
		seenKey[d.Key] = true
		writeDef(&b, d, fmt.Sprintf("%q:", d.Key))
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("gofmt 失败: %w\n--- 原始输出 ---\n%s", err, b.String())
	}
	return src, nil
}

func writeDef(b *strings.Builder, d MsgDef, keyPrefix string) {
	fmt.Fprintf(b, "\t%s {Name: %q, Key: %q, ID: %d, Desc: %q, Format: %q, Fields: ",
		keyPrefix, d.Name, d.Key, d.ID, d.Desc, d.Format)
	if len(d.Fields) == 0 {
		b.WriteString("nil")
	} else {
		b.WriteString("[]byte{")
		for i, f := range d.Fields {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "%d", f)
		}
		b.WriteString("}")
	}
	fmt.Fprintf(b, ", VarArgs: %v},\n", d.VarArgs)
}
